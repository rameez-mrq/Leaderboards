#!/usr/bin/env node
/**
 * Generate one submission token per team.
 *
 * Usage:
 *   node scripts/generate-team-tokens.js team-a team-b team-c
 *   node scripts/generate-team-tokens.js --file student-ids.txt   (one id per line)
 *
 * Writes (both gitignored):
 *   team-tokens.private.csv  student_id,token  -> give each team ONLY its own token
 *                                                 (they store it as LEADERBOARD_API_TOKEN)
 *   team-tokens.sql          inserts of the hashes -> run in the Supabase SQL editor
 */
import { randomBytes, createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const args = process.argv.slice(2);
let ids = args;
if (args[0] === '--file') {
	ids = readFileSync(args[1], 'utf-8').split(/\r?\n/);
}
ids = [...new Set(ids.map((s) => s.trim()).filter(Boolean))];

if (ids.length === 0) {
	console.error('Usage: node scripts/generate-team-tokens.js <student_id...> | --file ids.txt');
	process.exit(1);
}

const sqlQuote = (s) => `'${s.replace(/'/g, "''")}'`;
const csvQuote = (s) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);

const csv = ['student_id,token'];
const sql = ['-- Generated by scripts/generate-team-tokens.js', 'insert into team_tokens (token_hash, student_id) values'];
const values = [];

for (const id of ids) {
	const token = `cs7is3_${randomBytes(24).toString('base64url')}`;
	const hash = createHash('sha256').update(token).digest('hex');
	csv.push(`${csvQuote(id)},${token}`);
	values.push(`  (${sqlQuote(hash)}, ${sqlQuote(id)})`);
}
sql.push(values.join(',\n') + ';');

writeFileSync('team-tokens.private.csv', csv.join('\n') + '\n', { mode: 0o600 });
writeFileSync('team-tokens.sql', sql.join('\n') + '\n');
console.log(`Generated ${ids.length} tokens.`);
console.log('  team-tokens.sql          -> run in Supabase SQL editor');
console.log('  team-tokens.private.csv  -> distribute each token to its team only, then delete');
